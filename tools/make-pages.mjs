// Writes /<key>/index.html for every app that is not live, from apps.js. Run: node tools/make-pages.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import vm from "node:vm";

const ctx = {};
vm.runInNewContext(readFileSync("apps.js", "utf8") + "\nthis.APPS = APPS;", ctx);
const nav = readFileSync("index.html", "utf8").match(/<header class="nav-wrap">[\s\S]*?<\/header>/)[0]
  .replaceAll('href="#top"', 'href="../"').replaceAll('href="#', 'href="../#').replaceAll('src="assets/', 'src="../assets/');
const foot = readFileSync("index.html", "utf8").match(/<footer class="footer">[\s\S]*?<\/footer>/)[0].replaceAll('src="assets/', 'src="../assets/');

for (const a of ctx.APPS) {
  if (a.url) { if (existsSync(a.key)) rmSync(a.key, { recursive: true }); continue; }
  mkdirSync(a.key, { recursive: true });
  writeFileSync(`${a.key}/index.html`, `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${a.word}Lift · Lift Apps by AIYun</title>
<meta name="description" content="${a.word}Lift: ${a.desc.replaceAll('"', "&quot;")}" />
<meta name="theme-color" content="#FBF8F2" />
<link rel="icon" href="../assets/favicon.png" />
<link rel="preconnect" href="https://fonts.googleapis.com" />
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600&family=Noto+Serif+SC:wght@600;700;900&family=Noto+Sans+SC:wght@400;500&display=swap" rel="stylesheet" />
<link rel="stylesheet" href="../styles.css" />
</head>
<body data-app="${a.key}">
<!-- Generated by tools/make-pages.mjs; edit apps.js / details.js instead. -->
${nav}
<main id="intro"></main>
${foot}
<script src="../icons.js"></script>
<script src="../apps.js"></script>
<script src="../details.js"></script>
<script src="../i18n.js"></script>
<script src="../app.js"></script>
</body>
</html>
`);
}
console.log("pages:", ctx.APPS.filter((a) => !a.url).map((a) => a.key).join(" "));
