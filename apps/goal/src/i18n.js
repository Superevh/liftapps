export function makeT(lang) {
  const d = STR[lang] || STR.en;
  return (key, vars) => {
    let s = d[key] ?? STR.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
    return s;
  };
}
